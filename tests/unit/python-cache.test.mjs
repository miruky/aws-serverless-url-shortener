import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { inspectProject } from '../../tools/trace/model.mjs';

test('Python bytecode generated by a test run does not become an undocumented implementation', t => {
  const root = mkdtempSync(join(tmpdir(), 'shortener-trace-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(join(root, 'src/__pycache__'), { recursive: true });
  writeFileSync(join(root, 'src/__pycache__/example.cpython-312.pyc'), 'compiled cache');
  writeFileSync(join(root, 'src/new.py'), 'unowned source');
  writeFileSync(join(root, 'trace.config.json'), JSON.stringify({schemaVersion:1,documents:[],managedRoots:['src'],managedFiles:[],lockFile:'trace.lock.json'}));
  const unowned = inspectProject(root).findings.filter(f => f.code === 'UNMANAGED_FILE').map(f => f.path);
  assert.deepEqual(unowned, ['src/new.py']);
});
